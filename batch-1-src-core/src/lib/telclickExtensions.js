// השוואה לאחר ניקוי רווחים מקדימים/עוקבים וכיווץ רווחים כפולים
const normalizeName = (n) => (n || "").trim().replace(/\s+/g, " ");
const NORMALIZED_EXT = Object.fromEntries(
  Object.entries(DIRECT_EXT).map(([k, v]) => [normalizeName(k), v])
);

// מרחק לוינשטיין להתאמה פוג'יטיבית של שמות
const levenshtein = (a, b) => {
  const m = a.length, n = b.length;
  if (!m) return n; if (!n) return m;
  let prev = Array.from({ length: n + 1 }, (_, i) => i);
  let curr = new Array(n + 1);
  for (let i = 1; i <= m; i++) {
    curr[0] = i;
    for (let j = 1; j <= n; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      curr[j] = Math.min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost);
    }
    [prev, curr] = [curr, prev];
  }
  return prev[n];
};
const similarity = (a, b) => 1 - levenshtein(a, b) / Math.max(a.length, b.length || 1);

export const getExtension = (name) => {
  const n = normalizeName(name);
  if (!n) return "";
  if (NORMALIZED_EXT[n]) return NORMALIZED_EXT[n];
  // גיבוי 1: התאמת הכלה — שם אחד מופיע בתוך השני (למשל "שרה לודמיר" בתוך "שרה לודמיר מזכירה")
  const contained = [];
  for (const [k, v] of Object.entries(NORMALIZED_EXT)) {
    if (Math.min(n.length, k.length) >= 6 && (k.includes(n) || n.includes(k))) contained.push(v);
  }
  if (contained.length === 1) return contained[0];
  // גיבוי 2: התאמה פוג'יטיבית לפי מידת דמיון
  let best = "", bestScore = 0;
  for (const [k, v] of Object.entries(NORMALIZED_EXT)) {
    const s = similarity(n, k);
    if (s > bestScore) { bestScore = s; best = v; }
  }
  return bestScore >= 0.82 ? best : "";
};

// מחזיר רשימת שמות נציגים שאינם מופיעים במפת השלוחות
export const findUnmapped = (reps) =>
  reps
    .map((r) => r.name)
    .filter((n) => !!n && !getExtension(n))
    .filter((v, i, a) => a.indexOf(v) === i)
